#!/bin/sh

set -e

################################################################################
# repo
################################################################################
helm repo add stable https://charts.helm.sh/stable
helm repo add postgres-operator-charts https://opensource.zalando.com/postgres-operator/charts/postgres-operator
helm repo add opensearch https://opensearch-project.github.io/helm-charts/
helm repo add fusionauth https://fusionauth.github.io/charts
helm repo update > /dev/null


################################################################################
# chart
################################################################################
STACK="fusionauth"
CHART="fusionauth/fusionauth"
CHART_VERSION="1.69.3"
NAMESPACE="fusionauth"

# Preserve database credentials when upgrading from the previous FusionAuth chart.
# Legacy releases used the Helm-managed fusionauth-credentials Secret, whose
# password may differ from the credentials generated by the Postgres operator.
ensure_database_credentials_secret() {
  DATABASE_CREDENTIALS_SECRET="fusionauth-database-credentials"

  if kubectl get secret "$DATABASE_CREDENTIALS_SECRET" \
    --namespace "$NAMESPACE" >/dev/null 2>&1; then
    DB_PASSWORD=$(kubectl get secret "$DATABASE_CREDENTIALS_SECRET" \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.password}')
    ROOT_PASSWORD=$(kubectl get secret "$DATABASE_CREDENTIALS_SECRET" \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.rootpassword}')
    if [ -z "$DB_PASSWORD" ] || [ -z "$ROOT_PASSWORD" ]; then
      echo "PostgreSQL credentials are missing from $DATABASE_CREDENTIALS_SECRET" >&2
      exit 1
    fi
    return
  fi

  if kubectl get secret fusionauth-credentials \
    --namespace "$NAMESPACE" >/dev/null 2>&1; then
    # Preserve credentials from releases installed with the previous chart.
    DB_PASSWORD=$(kubectl get secret fusionauth-credentials \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.password}')
    ROOT_PASSWORD=$(kubectl get secret fusionauth-credentials \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.rootpassword}')
  else
    if ! kubectl get \
      secret/fusionauth.db-postgresql.credentials.postgresql.acid.zalan.do \
      secret/postgres.db-postgresql.credentials.postgresql.acid.zalan.do \
      --namespace "$NAMESPACE" >/dev/null 2>&1; then
      echo "PostgreSQL credential Secrets are not available" >&2
      exit 1
    fi

    # Installs without the legacy Helm Secret use the operator credentials.
    DB_PASSWORD=$(kubectl get secret \
      fusionauth.db-postgresql.credentials.postgresql.acid.zalan.do \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.password}')
    ROOT_PASSWORD=$(kubectl get secret \
      postgres.db-postgresql.credentials.postgresql.acid.zalan.do \
      --namespace "$NAMESPACE" \
      -o jsonpath='{.data.password}')
  fi

  if [ -z "$DB_PASSWORD" ] || [ -z "$ROOT_PASSWORD" ]; then
    echo "PostgreSQL credentials are missing from the source Secret" >&2
    exit 1
  fi

  cat <<EOF | kubectl apply -f -
apiVersion: v1
kind: Secret
metadata:
  name: $DATABASE_CREDENTIALS_SECRET
  namespace: $NAMESPACE
type: Opaque
data:
  password: $DB_PASSWORD
  rootpassword: $ROOT_PASSWORD
EOF
}

if [ -z "${MP_KUBERNETES}" ]; then
  # use local version of values.yml
  ROOT_DIR=$(git rev-parse --show-toplevel)
  VALUES="$ROOT_DIR/stacks/fusionauth/values.yml"
else
  # use github hosted master version of values.yml
  VALUES="https://raw.githubusercontent.com/digitalocean/marketplace-kubernetes/master/stacks/fusionauth/values.yml"
fi

ensure_database_credentials_secret

helm upgrade "$STACK" "$CHART" \
--namespace "$NAMESPACE" \
--values "$VALUES" \
--version "$CHART_VERSION" \
--set database.dbUser.username="fusionauth" \
--set search.host=opensearch-cluster-master
